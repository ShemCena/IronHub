import { NextResponse } from "next/server";
import QRCode from "qrcode";
import { prisma } from "@/lib/db/prisma";
import { requireMemberSession } from "@/lib/auth/member-session";
import {
  decryptQrToken,
  encryptQrToken,
  generateOpaqueQrToken,
} from "@/lib/qr/token";
import { writeAuditLog } from "@/lib/audit/log";

export async function GET() {
  try {
    const session = await requireMemberSession();
    const member = await prisma.member.findUnique({
      where: { id: session.memberId },
      include: {
        memberships: { orderBy: { endDate: "desc" }, take: 1 },
        qrCredentials: {
          where: { isActive: true },
          orderBy: { issuedAt: "desc" },
          take: 1,
        },
        attendanceRecords: {
          where: { outcome: "APPROVED" },
          orderBy: { checkedInAt: "desc" },
          take: 8,
        },
      },
    });

    if (!member) {
      return NextResponse.json({ error: "Member not found." }, { status: 404 });
    }

    const activeCred = member.qrCredentials[0] ?? null;
    let qrDataUrl: string | null = null;
    let rawToken: string | null = null;

    if (activeCred?.tokenCiphertext) {
      rawToken = decryptQrToken(activeCred.tokenCiphertext);
      if (rawToken) {
        qrDataUrl = await QRCode.toDataURL(rawToken, {
          errorCorrectionLevel: "M",
          margin: 4,
          width: 300,
          color: { dark: "#000000", light: "#FFFFFF" },
        });
      }
    }

    return NextResponse.json({
      member: {
        id: member.id,
        memberCode: member.memberCode,
        name: `${member.firstName} ${member.lastName}`,
        email: member.email,
        phone: member.phone,
        status: member.status,
        planName: member.memberships[0]?.planNameSnapshot ?? "No Plan",
        expiryDate: member.memberships[0]?.endDate ?? null,
      },
      credential: activeCred
        ? {
            id: activeCred.id,
            tokenLast4: activeCred.tokenLast4,
            issuedAt: activeCred.issuedAt,
            hasRenderableToken: Boolean(qrDataUrl),
          }
        : null,
      qrDataUrl,
      tokenPreview: rawToken,
      recentVisits: member.attendanceRecords.map((a) => ({
        id: a.id,
        method: a.method,
        checkedInAt: a.checkedInAt,
      })),
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "Failed to load portal";
    const status = message.startsWith("Unauthorized") ? 401 : 500;
    return NextResponse.json({ error: message }, { status });
  }
}

/**
 * Self-service QR generation by the authenticated client/member.
 */
export async function POST() {
  try {
    const session = await requireMemberSession();
    const member = await prisma.member.findUnique({
      where: { id: session.memberId },
      include: {
        memberships: { orderBy: { endDate: "desc" }, take: 1 },
      },
    });

    if (!member || member.status === "ARCHIVED") {
      return NextResponse.json({ error: "Member account unavailable." }, { status: 400 });
    }

    const { rawToken, tokenHash, tokenLast4 } = generateOpaqueQrToken();
    const tokenCiphertext = encryptQrToken(rawToken);

    const credential = await prisma.$transaction(async (tx) => {
      await tx.qRCredential.updateMany({
        where: { memberId: member.id, isActive: true },
        data: {
          isActive: false,
          revokedAt: new Date(),
          revokedReason: "Regenerated by member in portal",
        },
      });

      const created = await tx.qRCredential.create({
        data: {
          memberId: member.id,
          tokenHash,
          tokenLast4,
          tokenCiphertext,
          isActive: true,
        },
      });

      await writeAuditLog(tx, {
        actorId: null,
        action: "MEMBER_QR_SELF_GENERATED",
        entityType: "QRCredential",
        entityId: created.id,
        metadata: { memberId: member.id, memberCode: member.memberCode, tokenLast4 },
      });

      return created;
    });

    const qrDataUrl = await QRCode.toDataURL(rawToken, {
      errorCorrectionLevel: "M",
      margin: 4,
      width: 300,
      color: { dark: "#000000", light: "#FFFFFF" },
    });

    return NextResponse.json({
      credential: {
        id: credential.id,
        tokenLast4: credential.tokenLast4,
        issuedAt: credential.issuedAt,
        hasRenderableToken: true,
      },
      qrDataUrl,
      tokenPreview: rawToken,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "Failed to generate QR pass";
    const status = message.startsWith("Unauthorized") ? 401 : 500;
    return NextResponse.json({ error: message }, { status });
  }
}
